import assert from "node:assert/strict";
import {randomBytes} from "node:crypto";
import {setTimeout as sleep} from "node:timers/promises";
const base="http://127.0.0.1:8787";
const auth="Basic "+Buffer.from("admin:synthetic-local-test-password-not-production").toString("base64");
const req=(path,options={})=>fetch(base+path,{...options,redirect:"error",signal:AbortSignal.timeout(5000)});
let ready=false;
for(let i=0;i<60;i++){try{if((await req("/health")).status===200){ready=true;break}}catch{}await sleep(500)}

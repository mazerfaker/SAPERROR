assert.equal(await post({...payload,unexpected:true}),400);
assert.equal(await post(payload),204);
assert.equal(await post({...payload,seconds:120,wins:2,losses:1,sector:3}),204);
assert.equal(await post(payload),204);
assert.equal(await post({...payload,mode:"classic",seconds:999}),204);

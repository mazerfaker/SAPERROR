const summary=async()=>{const r=await req("/api/summary",{headers:{Authorization:auth}});assert.equal(r.status,200);return r.json()};
const post=async x=>(await req("/v2/session",{method:"POST",headers:{"Content-Type":"application/json"},body:JSON.stringify(x)})).status;
assert.equal((await req("/api/summary")).status,401);
const initial=await summary();
assert.equal(initial.totals.sessions,0,"fresh isolated D1");
